struct __attribute__((packed)) DevIkRequest
{
    std::array<uint8_t, 16>      serial_number;
    std::array<uint8_t, 5>       dda_ordinal_number;
    std::array<uint8_t, 5>       fmc_ordinal_number;
    std::array<uint8_t, 96>      public_key;
    std::array<uint8_t, 32>      subject_serial_number;  // serial_number to printable value
    std::array<uint8_t, 20>      authority_key_identifier;
    std::array<uint8_t, 20>      subject_key_identifier;
    nv::spdm::certlib::Signature signature;
};

class DevIkHelper
{
private:
    static constexpr size_t MaxIkTemplateSize = sizeof(DevIkTemplateV3) > sizeof(DevIkTemplate)
                                                  ? sizeof(DevIkTemplateV3)
                                                  : sizeof(DevIkTemplate);

    std::array<uint8_t, MaxIkTemplateSize> _template_bytes{};
    uint32_t                               _template_size{};
    nv::spdm::certlib::Signature           _signature;

    template<typename TemplateType>
    void fill_template(TemplateType& templ, nv::spdm::ik::DevIkRequest& req);

public:
    // please make sure the input signature is fill with correct value
    DevIkHelper(nv::spdm::ik::DevIkRequest& req);
    void construct_cert(std::span<uint8_t>& input_buffer);
};
// Error codes for template comparison failures
enum class TemplateComparisonError : uint32_t
{
    Success                        = 0,
    SerialNumberMismatch           = 1,
    DdaOrdinalNumberMismatch       = 2,
    FmcOrdinalNumberMismatch       = 3,
    SubjectSerialNumberMismatch    = 4,
    PublicKeyMismatch              = 5,
    SubjectKeyIdentifierMismatch   = 6,
    AuthorityKeyIdentifierMismatch = 7,
    SignatureMismatch              = 8
};

// Check if two templates are the same.
// TemplateType must be either DevIkTemplate (V4) or DevIkTemplateV3 (V3).
// Both arguments must be the same type so that struct offsets align with cert bytes.
template<typename TemplateType>
TemplateComparisonError check_two_template_is_same(const TemplateType& template_1,
                                                   const TemplateType& template_2);
